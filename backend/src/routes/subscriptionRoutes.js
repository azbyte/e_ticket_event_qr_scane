const { Router } = require('express');
const { authMiddleware } = require('../middleware/authMiddleware');
const allowRoles = require('../middleware/roleMiddleware');
const controller = require('../controllers/subscriptionController');
const router = Router();
router.use(authMiddleware, allowRoles('organizer'));
router.get('/me', controller.getMySubscription);
router.post('/', controller.subscribe);
router.post('/cancel', controller.cancelSubscription);
router.get('/payments', controller.listMyPayments);
module.exports = router;
